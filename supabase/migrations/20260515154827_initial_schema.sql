-- =====================================================================
-- Koupreng initial schema (Postgres / Supabase)
-- =====================================================================
-- Auth is owned by Supabase (auth.users). app_users is a profile table
-- linked to auth.users by uuid. Token tables are removed (Supabase Auth
-- handles password reset / email verification).
-- =====================================================================

-- ---------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------
create type auth_provider as enum ('LOCAL', 'GOOGLE', 'TELEGRAM');
create type user_role     as enum ('ADMIN', 'USER');

-- ---------------------------------------------------------------------
-- Profiles linked to auth.users
-- ---------------------------------------------------------------------
create table public.app_users (
    id              uuid primary key references auth.users(id) on delete cascade,
    email           varchar(255) not null unique,
    full_name       varchar(120) not null,
    auth_provider   auth_provider not null default 'LOCAL',
    provider_id     varchar(255),
    role            user_role not null default 'USER',
    enabled         boolean not null default true,
    token_version   integer not null default 0,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),
    unique (auth_provider, provider_id)
);

-- ---------------------------------------------------------------------
-- Templates
-- ---------------------------------------------------------------------
create table public.templates (
    template_id   bigint generated by default as identity primary key,
    name          varchar(255) not null,
    category      varchar(50),
    thumbnail_url varchar(1000),
    preview_url   varchar(1000),
    is_premium    boolean not null default false,
    status        varchar(20),
    created_at    timestamptz default now()
);

-- ---------------------------------------------------------------------
-- Invitations
-- ---------------------------------------------------------------------
create table public.invitations (
    invitation_id      bigint generated by default as identity primary key,
    user_id            uuid not null references public.app_users(id) on delete cascade,
    template_id        bigint references public.templates(template_id) on delete set null,
    title              varchar(255) not null,
    slug               varchar(255) unique,
    event_type         varchar(50),
    event_date         date,
    event_time         time,
    venue_name         varchar(255),
    venue_address      varchar(1000),
    google_map_url     varchar(1000),
    host_name          varchar(255),
    partner_name       varchar(255),
    groom_name         varchar(255),
    bride_name         varchar(255),
    groom_father_name  varchar(255),
    groom_mother_name  varchar(255),
    bride_father_name  varchar(255),
    bride_mother_name  varchar(255),
    story_text         text,
    language_mode      varchar(20),
    visibility         varchar(20),
    access_password    varchar(255),
    rsvp_deadline      date,
    status             varchar(20),
    created_at         timestamptz default now(),
    updated_at         timestamptz default now()
);

create index idx_invitations_user on public.invitations(user_id);
create index idx_invitations_template on public.invitations(template_id);

