-- ---------------------------------------------------------------------
-- Auto-create app_users row on auth.users insert
-- ---------------------------------------------------------------------
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
begin
    insert into public.app_users (id, email, full_name, auth_provider, provider_id)
    values (
        new.id,
        coalesce(new.email, ''),
        coalesce(new.raw_user_meta_data ->> 'full_name', split_part(coalesce(new.email, ''), '@', 1)),
        case
            when (new.raw_app_meta_data ->> 'provider') = 'google'   then 'GOOGLE'::auth_provider
            when (new.raw_app_meta_data ->> 'provider') = 'telegram' then 'TELEGRAM'::auth_provider
            else 'LOCAL'::auth_provider
        end,
        new.raw_app_meta_data ->> 'provider_id'
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_auth_user();
